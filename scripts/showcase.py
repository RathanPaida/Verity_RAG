"""End-to-end showcase with real models: ingest -> hybrid search -> agent briefs (multi-source, conflict,
unanswerable, memory effect) -> full evaluation with LLM judge. Writes docs/RESULTS.md and eval/results/*.json.

    python -m scripts.showcase [--engagement acme-payments] [--skip-eval]
"""
from __future__ import annotations

import argparse
import json
import time
from datetime import datetime, timezone
from pathlib import Path

from eval.metrics import source_key
from verity import db
from verity.config import settings
from verity.embeddings import get_embedder
from verity.ingest.pipeline import ingest_path
from verity.llm.google_client import backend
from verity.memory import store as memory
from verity.retrieval.hybrid import Filters, backends, hybrid_search
from verity.service import ask

ROOT = Path(__file__).resolve().parents[1]
QUESTIONS = [
    ("Multi-source risk brief", "What are the top reliability risks of the payments platform? Prioritise by evidence."),
    ("Conflicting sources", "Is the payments platform really able to survive a regional outage?"),
    ("Structured records", "Which service had the most SEV1 and SEV2 incidents in 2024, and what were the causes?"),
    ("Unanswerable", "What was the result of the SOC 2 Type II audit?"),
]
MEMORY_Q = "How serious is the disaster-recovery risk for ledger-db right now?"
MEMORY = "Client CTO stated in workshop 2 that a ledger-db cross-region DR failover test passed on 2024-10-14."


def _brief_md(title: str, r: dict) -> str:
    m = r["metrics"]
    out = [f"### {title}", "", f"> **Q:** {r['question']}", "",
           f"`status: {r['status']}` · latency {m['latency_ms'] / 1000:.1f} s · LLM calls {m['llm_calls']} · "
           f"tool calls {m['tool_calls']} · tokens {m['tokens_in']:,} in / {m['tokens_out']:,} out · "
           f"cost ${m['cost_usd']:.4f} · models {', '.join(m.get('models', []))}", "",
           "**Supervisor plan:** " + "; ".join(f"{p['id']} ({p['specialist']}) {p['question']}" for p in r["plan"]),
           "", r["answer"].strip(), ""]
    if r["conflicts"]:
        out += ["**Conflicts flagged:**"] + [f"- {c['description']} (A: {c['side_a']}, B: {c['side_b']})"
                                              for c in r["conflicts"]] + [""]
    if r["citations"]:
        out += ["<details><summary>Citations (exact passages)</summary>", ""]
        for c in r["citations"]:
            passage = " ".join(c["passage"].split())[:300]
            out.append(f"- **[{c['label']}]** `{c['source_id']}` › {' › '.join(c['section_path'] or [])}: _{passage}_")
        out += ["", "</details>", ""]
    v = r["verification"]
    if v:
        out.append(f"Verifier route: `{v.get('route')}` (attempt {v.get('attempt')}); "
                   f"dropped unsupported claims: {len(v.get('unsupported') or [])}")
        out.append("")
    return "\n".join(out)


def render(st: dict) -> str:
    cfg, started = st["config"], st["started"]
    md = [f"# Verity: results from a real run ({started:%Y-%m-%d})", "",
          "Generated by `python -m scripts.showcase`. Everything below is real model output; nothing was edited.", "",
          "## Configuration", "", "| | |", "|---|---|"]
    md += [f"| {k} | `{v}` |" for k, v in cfg.items()]
    models_used = sorted({m for _, r in st.get("briefs", []) for m in r["metrics"].get("models", [])})
    md += ["", f"Models that actually answered (after fallbacks): `{', '.join(models_used) or 'n/a'}`. "
           f"Wall time so far {st.get('elapsed', 0) / 60:.1f} min.", ""]
    if "mongomock" in cfg["mongo"]:
        md += ["> **Note:** this run used an in-process MongoDB with the app's Python cosine / BM25 retrieval "
               "fallbacks, because no Atlas cluster was available on the build machine. With `MONGODB_URI` pointing at "
               "Atlas, the same code uses `$vectorSearch` + `$search`. Re-run this script to regenerate.", ""]
    md += ["## 1. Import", "", "| source | status | chunks |", "|---|---|---|"]
    md += [f"| `{x['source_id']}` | {x['status']} | {x['chunks']} |" for x in st["ingest"]]
    if st.get("search"):
        md += ["", "## 2. Keyword vs semantic vs hybrid (top-3 passages)", "", "| query | mode | top results |",
               "|---|---|---|"]
        md += [f"| `{q}` | {m} | {'<br>'.join(r)} |" for q, m, r in st["search"]]
    if st.get("briefs"):
        md += ["", "## 3. Agent briefs", ""] + [_brief_md(t, r) for t, r in st["briefs"]]
    if st.get("memory"):
        b, a = st["memory"]
        md += ["## 4. Memory changes the next brief", "", f"Stored memory (`client_statement`): _{MEMORY}_", "",
               _brief_md("Before the memory", b), _brief_md("After the memory", a)]
    report = st.get("eval")
    if report:
        k = report["k"]
        md += ["## 5. Evaluation (golden set: `eval/golden.jsonl`, 12 questions incl. 2 unanswerable)", "",
               f"| mode | recall@{k} | hit@{k} | MRR | nDCG@{k} |", "|---|---|---|---|---|"]
        md += [f"| {r['mode']} | {r['recall']:.3f} | {r['hit']:.3f} | {r['mrr']:.3f} | {r['ndcg']:.3f} |"
               for r in report["retrieval"]]
        ag = report["agent"]
        fmt = lambda v: "n/a" if v is None or v != v else f"{v:.2f}"  # noqa: E731 - NaN-safe
        sec = lambda v: "n/a" if v is None or v != v else f"{v / 1000:.1f} s"  # noqa: E731
        md += ["", "| abstention accuracy | citation precision | faithfulness (LLM judge) | p50 latency | p95 latency | "
               "mean cost / request | errors |", "|---|---|---|---|---|---|---|",
               f"| {fmt(ag['abstention_accuracy'])} | {fmt(ag['citation_precision'])} | {fmt(ag['faithfulness'])} | "
               f"{sec(ag['p50_latency_ms'])} | {sec(ag['p95_latency_ms'])} | ${ag['mean_cost_usd']:.4f} | "
               f"{ag.get('errors', 0)} |",
               "", "| question | status | abstention ok | citation precision | faithfulness |", "|---|---|---|---|---|"]
        md += [f"| {q['id']} | {q['status']} | {'✅' if q['abstention_correct'] else '❌'} | "
               f"{fmt(q['citation_precision'])} | {fmt(q.get('faithfulness', float('nan')))} |"
               for q in ag["per_question"]]
    return "\n".join(md) + "\n"


def save(st: dict, t0: float) -> None:
    st["elapsed"] = time.perf_counter() - t0
    stamp = st["started"].strftime("%Y%m%d-%H%M")
    res_dir = ROOT / "eval" / "results"
    res_dir.mkdir(parents=True, exist_ok=True)
    (res_dir / f"showcase-{stamp}.json").write_text(json.dumps(
        {**st, "briefs": [{"title": t, **r} for t, r in st.get("briefs", [])]}, default=str, indent=1),
        encoding="utf-8")
    (ROOT / "docs" / "RESULTS.md").write_text(render(st), encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engagement", default="acme-payments")
    ap.add_argument("--skip-eval", action="store_true")
    a = ap.parse_args()
    eng = a.engagement
    t0 = time.perf_counter()
    st: dict = {"started": datetime.now(timezone.utc)}

    print("1) ingest")
    st["ingest"] = ingest_path(ROOT / "data" / "sample", eng)
    st["config"] = {"llm_backend": backend(), "model_fast": settings.model_fast,
                    "model_strong": settings.model_strong, "fallbacks": settings.model_fallbacks,
                    "embeddings": get_embedder().name, "embedding_dim": settings.embedding_dim,
                    "mongo": "mongomock (in-process)" if db.is_mock() else "atlas"}

    print("2) hybrid search check")
    st["search"] = []
    for q in ("ERR-4471", "database failover to another region"):
        for mode in ("vector", "text", "hybrid"):
            hits = hybrid_search(q, Filters(eng), k=3, mode=mode)
            st["search"].append((q, mode, [source_key(h.source_id) + " › " + " › ".join(h.section_path[-1:])
                                           for h in hits]))
    st["config"]["retrieval_backends"] = backends()
    save(st, t0)

    print("3) agent runs")
    st["briefs"] = []
    for title, q in QUESTIONS:
        r = ask(q, eng, use_cache=False)
        r["question"] = q
        st["briefs"].append((title, r))
        print(f"   {title}: {r['status']} cites={len(r['citations'])} {r['metrics']}")
        save(st, t0)

    print("4) memory effect")
    before = ask(MEMORY_Q, eng, use_cache=False)
    before["question"] = MEMORY_Q
    memory.remember(eng, "analyst", "client_statement", MEMORY)
    after = ask(MEMORY_Q, eng, use_cache=False)
    after["question"] = MEMORY_Q
    st["memory"] = (before, after)
    save(st, t0)
    print(f"   before={before['status']} after={after['status']} memories_used={len(after['memories_used'])}")

    if not a.skip_eval:
        print("5) evaluation (retrieval x3 modes + full agent + LLM judge)")
        from eval.run_eval import _print, run
        st["eval"] = run(eng, ["vector", "text", "hybrid"], 5, agent=True, judge=True)
        _print(st["eval"], verbose=False)
        save(st, t0)
    print(f"done in {(time.perf_counter() - t0) / 60:.1f} min -> docs/RESULTS.md")


if __name__ == "__main__":
    main()
