"""Retrieval ablations: chunk size x search mode x RRF weights, on the golden set.

    python -m eval.ablate [--chunks 200,350,600] [--k 5]      -> docs/ABLATIONS.md + eval/results/ablations-*.json

Each chunk size is ingested into its own engagement (abl-c<size>) so configurations don't interfere.
Only retrieval is evaluated (no LLM calls); embeddings use the configured provider.
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

from verity.config import settings
from verity.embeddings import get_embedder
from verity.ingest.pipeline import ingest_path

from .run_eval import eval_retrieval, load_golden

ROOT = Path(__file__).resolve().parents[1]
WEIGHTS = [(1.0, 1.0), (1.0, 0.5), (0.5, 1.0)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--chunks", default="200,350,600")
    ap.add_argument("--k", type=int, default=5)
    a = ap.parse_args()
    golden = load_golden()
    rows = []
    seen_counts: dict[int, int] = {}
    for size in (int(x) for x in a.chunks.split(",")):
        eng = f"abl-c{size}"
        settings.chunk_tokens = size
        n_chunks = sum(r["chunks"] for r in ingest_path(ROOT / "data" / "sample", eng))
        if n_chunks in seen_counts:  # identical chunking -> identical retrieval; don't spend quota re-measuring
            print(f"chunk_tokens={size} produces the same {n_chunks} chunks as {seen_counts[n_chunks]}; skipped")
            continue
        seen_counts[n_chunks] = size
        for mode in ("vector", "text"):
            r = eval_retrieval(eng, mode, a.k, golden)
            rows.append({"chunk_tokens": size, "chunks": n_chunks, "mode": mode, "weights": None, **_m(r)})
            print(rows[-1])
        for w in WEIGHTS:
            settings.vector_weight, settings.text_weight = w
            r = eval_retrieval(eng, "hybrid", a.k, golden)
            rows.append({"chunk_tokens": size, "chunks": n_chunks, "mode": "hybrid", "weights": list(w), **_m(r)})
            print(rows[-1])
        settings.vector_weight = settings.text_weight = 1.0

    stamp = datetime.now(timezone.utc)
    (ROOT / "eval" / "results").mkdir(exist_ok=True)
    (ROOT / "eval" / "results" / f"ablations-{stamp:%Y%m%d-%H%M}.json").write_text(json.dumps(rows, indent=1))
    best = max(rows, key=lambda r: (r["recall"], r["mrr"]))
    md = [f"# Retrieval ablations ({stamp:%Y-%m-%d})", "",
          f"Golden set: {rows[0]['n']} answerable questions with expected sources · k={a.k} · "
          f"embeddings `{get_embedder().name}` · generated by `python -m eval.ablate`.", "",
          "| chunk tokens | chunks | mode | RRF weights (vector, keyword) | recall@k [95% CI] | MRR [95% CI] | nDCG@k |",
          "|---|---|---|---|---|---|---|"]
    for r in rows:
        mark = " **(best)**" if r is best else ""
        md.append(f"| {r['chunk_tokens']} | {r['chunks']} | {r['mode']}{mark} | {r['weights'] or '-'} | "
                  f"{r['recall']:.3f} [{r['recall_ci95'][0]:.2f}-{r['recall_ci95'][1]:.2f}] | "
                  f"{r['mrr']:.3f} [{r['mrr_ci95'][0]:.2f}-{r['mrr_ci95'][1]:.2f}] | {r['ndcg']:.3f} |")
    md += ["", "Confidence intervals are percentile bootstrap over questions; overlapping intervals mean the "
               "difference is not established at this sample size."]
    (ROOT / "docs" / "ABLATIONS.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("best:", best)


def _m(r: dict) -> dict:
    return {k: r[k] for k in ("n", "recall", "mrr", "ndcg", "recall_ci95", "mrr_ci95", "cross_tenant_leaks")}


if __name__ == "__main__":
    main()
